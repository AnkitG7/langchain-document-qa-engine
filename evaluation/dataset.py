"""Evaluation Dataset Schemas & Synthetic Test Case Generator.

Demonstrates:
- Structured schema for RAG evaluation samples
- JSON serialization and benchmark dataset loading
- Automated synthetic QA pair generation from document chunks
"""

import json
import uuid
import re
from pathlib import Path
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field
from langchain_core.documents import Document
from langchain_core.prompts import ChatPromptTemplate
from langchain_core.output_parsers import StrOutputParser
from langchain_core.language_models.chat_models import BaseChatModel

from llm.provider import get_chat_model


class EvalSample(BaseModel):
    """Single evaluation data point for RAG benchmarking."""
    id: str = Field(default_factory=lambda: str(uuid.uuid4())[:8])
    question: str
    ground_truth: str = Field(default="", description="Reference ground-truth answer")
    retrieved_context: str = Field(default="", description="Context retrieved by the pipeline")
    answer: str = Field(default="", description="Answer generated by the pipeline")
    metadata: Dict[str, Any] = Field(default_factory=dict)


class EvalDataset(BaseModel):
    """Collection of evaluation samples with serialization helpers."""
    name: str = "DocMind Benchmark Dataset"
    samples: List[EvalSample] = Field(default_factory=list)

    def add_sample(self, sample: EvalSample) -> None:
        self.samples.append(sample)

    def save_json(self, file_path: str) -> None:
        """Saves dataset to a JSON file."""
        Path(file_path).parent.mkdir(parents=True, exist_ok=True)
        with open(file_path, "w", encoding="utf-8") as f:
            json.dump(self.model_dump(), f, indent=2, ensure_ascii=False)

    @classmethod
    def load_json(cls, file_path: str) -> "EvalDataset":
        """Loads dataset from a JSON file."""
        with open(file_path, "r", encoding="utf-8") as f:
            data = json.load(f)
        return cls(**data)


class SyntheticDataGenerator:
    """Generates synthetic QA test pairs from document chunks using an LLM."""

    def __init__(self, llm: Optional[BaseChatModel] = None):
        self.llm = llm or get_chat_model()
        prompt = ChatPromptTemplate.from_messages([
            (
                "system",
                "You are an expert test dataset creator for document evaluation. "
                "Given a document excerpt, generate ONE high-quality factual question and its ground-truth answer "
                "based STRICTLY on the excerpt. Do not ask subjective questions.\n\n"
                "Respond in this exact JSON format:\n"
                '{{"question": "<question string>", "ground_truth": "<concise factual answer string>"}}',
            ),
            (
                "human",
                "Document Excerpt:\n{chunk}\n\nJSON Output:",
            ),
        ])
        self.chain = prompt | self.llm | StrOutputParser()

    def generate_sample_from_chunk(self, doc: Document) -> Optional[EvalSample]:
        """Generates an EvalSample from a single Document chunk."""
        if len(doc.page_content.strip()) < 40:
            return None

        try:
            raw = self.chain.invoke({"chunk": doc.page_content[:1200]}).strip()
            data = json.loads(re.search(r"\{.*\}", raw, re.DOTALL).group(0))
            return EvalSample(
                question=data["question"],
                ground_truth=data["ground_truth"],
                metadata={
                    "source": doc.metadata.get("source", "unknown"),
                    "filename": doc.metadata.get("filename", "unknown"),
                },
            )
        except Exception:
            return None

    def generate_dataset(
        self,
        documents: List[Document],
        max_samples: int = 5,
        dataset_name: str = "Synthetic RAG Evaluation Dataset",
    ) -> EvalDataset:
        """Generates an EvalDataset from a collection of Document chunks."""
        dataset = EvalDataset(name=dataset_name)
        for doc in documents[:max_samples]:
            sample = self.generate_sample_from_chunk(doc)
            if sample:
                dataset.add_sample(sample)
        return dataset
